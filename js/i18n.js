let currentLang = localStorage.getItem('lang') || 'zh-HK';

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('lang', lang);
  document.documentElement.lang = lang;

  const isEn = lang === 'en';
  document.body.classList.toggle('lang-en', isEn);

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const text = translations[lang][key];
    if (text !== undefined) {
      if (text.includes('<br>')) {
        el.innerHTML = text;
      } else {
        el.textContent = text;
      }
    }
  });

  const langToggle = document.getElementById('langToggle');
  if (langToggle) {
    const spans = langToggle.querySelectorAll('span:not(.lang-divider)');
    if (isEn) {
      spans[0].textContent = '繁';
      spans[0].classList.remove('lang-active');
      spans[0].classList.add('lang-inactive');
      spans[1].textContent = 'EN';
      spans[1].classList.add('lang-active');
      spans[1].classList.remove('lang-inactive');
    } else {
      spans[0].textContent = '繁';
      spans[0].classList.add('lang-active');
      spans[0].classList.remove('lang-inactive');
      spans[1].textContent = 'EN';
      spans[1].classList.remove('lang-active');
      spans[1].classList.add('lang-inactive');
    }
  }

  const heroTitleEn = document.querySelector('.hero-title-en');
  if (heroTitleEn) {
    heroTitleEn.style.display = isEn ? 'none' : 'block';
  }

  const heroTitleZh = document.querySelector('.hero-title-zh');
  if (heroTitleZh && isEn) {
    heroTitleZh.style.fontSize = 'clamp(1.5rem, 3.5vw, 2.8rem)';
  } else if (heroTitleZh) {
    heroTitleZh.style.fontSize = '';
  }

  const contactValueEn = document.querySelector('.contact-value-en');
  if (contactValueEn) {
    contactValueEn.style.display = isEn ? 'none' : 'block';
  }
}

function toggleLanguage() {
  setLanguage(currentLang === 'zh-HK' ? 'en' : 'zh-HK');
}

function t(key) {
  return translations[currentLang][key] || key;
}

document.addEventListener('DOMContentLoaded', () => {
  setLanguage(currentLang);
});
